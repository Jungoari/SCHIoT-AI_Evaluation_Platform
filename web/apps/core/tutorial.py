TITLES = {"participant": "학생", "admin1": "조교", "admin2": "교수"}


def role_key(user) -> str:
    """안내할 역할: 교수 > 조교 > 학생 (여러 역할이면 더 많은 일을 하는 쪽 안내)"""
    if user.is_admin2:
        return "admin2"
    if user.memberships.filter(is_active=True, role=Role.ADMIN1).exists():
        return "admin1"
    return "participant"


def context(request) -> dict:
    """템플릿 공통 값: 튜토리얼을 띄울지와 내용"""
    user = getattr(request, "user", None)
    if not user or not user.is_authenticated:
        return {}
    replay = request.GET.get("tutorial") == "1"
    if user.tutorial_done_at is not None and not replay:
        return {}
    key = role_key(user)
    return {"tutorial": {"role": key, "role_title": TITLES[key], "steps": STEPS[key]}}
