def total_seconds() -> int:
    return sum(sec for sec, _ in NOTES.values())


def write_markdown(path: Path) -> None:
    lines = [
        "# 발표 대본 (15분)",
        "",
        f"> 슬라이드 {len(NOTES)}장 · 합계 약 {total_seconds() // 60}분 {total_seconds() % 60}초 (질의응답 제외)",
        "> 같은 내용이 PPT 각 슬라이드의 발표자 노트에 들어 있다 — `scripts/presentation_notes.py` 에서 고친 뒤 `scripts/build_presentation.py` 재실행",
        "",
    ]
    elapsed = 0
    for no, (sec, body) in NOTES.items():
        lines += [f"## {no}. ({sec}초 · 누적 {(elapsed + sec) // 60}:{(elapsed + sec) % 60:02d})", ""]
        lines += [body.replace("\n", "  \n"), ""]
        elapsed += sec
    lines += ["---", "", "## 예상 질문", ""]
    for q, a in QA:
        lines += [f"**Q. {q}**", "", a, ""]
    path.write_text("\n".join(lines), encoding="utf-8")


